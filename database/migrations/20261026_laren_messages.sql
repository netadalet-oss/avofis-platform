create table if not exists public.laren_messages (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.laren_requests(id) on delete cascade,
  sender_user_id uuid not null default auth.uid() references auth.users(id),
  body text not null check (char_length(btrim(body)) between 1 and 3000),
  created_at timestamptz not null default now()
);
create index if not exists laren_messages_by_request
  on public.laren_messages (request_id, created_at asc, id);

alter table public.laren_messages enable row level security;
revoke all on public.laren_messages from anon, authenticated;
grant select, insert on public.laren_messages to authenticated;

drop policy if exists laren_messages_read on public.laren_messages;
create policy laren_messages_read
  on public.laren_messages for select to authenticated using (
    (select public.laren_is_staff()) or exists (
      select 1 from public.laren_requests r
      where r.id = request_id and r.owner_user_id = (select auth.uid())
    )
  );
drop policy if exists laren_messages_write on public.laren_messages;
create policy laren_messages_write
  on public.laren_messages for insert to authenticated with check (
    sender_user_id = (select auth.uid()) and exists (
      select 1 from public.laren_requests r
      where r.id = request_id
        and r.status <> 'closed'
        and (r.owner_user_id = (select auth.uid()) or (select public.laren_is_staff()))
    )
  );

-- One initial history entry per new case, generated by database trigger.
-- Security definer is narrowly scoped to this one append-only event.
create or replace function public.laren_on_request_created()
returns trigger language plpgsql security definer
set search_path = ''
as $$
begin
  insert into public.laren_request_events
    (request_id, actor_user_id, status, message, visibility)
  values (new.id, new.owner_user_id, 'new', 'Başvurunuz alındı.', 'client');
  return new;
end;
$$;
revoke all on function public.laren_on_request_created() from public;
drop trigger if exists trg_laren_request_created on public.laren_requests;
create trigger trg_laren_request_created
after insert on public.laren_requests
for each row execute function public.laren_on_request_created();

-- Existing cases: backfill ONLY if no event is recorded yet.
insert into public.laren_request_events (request_id, actor_user_id, status, message, visibility)
select r.id, r.owner_user_id, 'new', 'Başvuru kaydı oluşturuldu.', 'client'
from public.laren_requests r
where not exists (
  select 1 from public.laren_request_events e where e.request_id = r.id
);
